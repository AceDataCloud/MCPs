#!/usr/bin/env python3
"""Generate ordinary hosted deployment entrypoints from two small templates."""

import argparse
import copy
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
# These are the current owned resources, not a recursive production-directory apply.
RESOURCES = ("deployment.yaml", "service.yaml", "ingress.yaml")
EXTRA_RESOURCES = ("oauth-redis.yaml",)


def hosted_services(root: Path = ROOT) -> list[str]:
    catalog = json.loads((root / "scripts/mcp_catalog.json").read_text())["services"]
    return sorted(
        alias
        for alias, entry in catalog.items()
        if entry["status"] == "active"
        and (root / alias / "deploy/production/deployment.yaml").is_file()
    )


def sync(root: Path = ROOT, *, check: bool = False) -> list[Path]:
    shell = (root / "shared/deploy/run.sh.template").read_text()
    workflow_template = yaml.safe_load(
        (root / "shared/deploy/workflow.yaml").read_text()
    )
    stale = []
    for alias in hosted_services(root):
        package = root / alias
        resources = [
            *RESOURCES,
            *(
                name
                for name in EXTRA_RESOURCES
                if (package / "deploy/production" / name).exists()
            ),
        ]
        if any(
            not (package / "deploy/production" / name).is_file() for name in resources
        ):
            raise ValueError(f"Incomplete deployment resources: {alias}")
        workflow = copy.deepcopy(workflow_template)
        quality = package / ".github/workflows/quality.yml"
        if quality.exists():
            # Preserve the package's existing quality contract on this same checkout.
            steps = yaml.safe_load(quality.read_text())["jobs"]["quality"]["steps"]
            steps = [
                step
                for step in steps
                if not step.get("uses", "").startswith(
                    ("actions/checkout@", "actions/setup-python@")
                )
            ]
            workflow["jobs"]["run"]["steps"][2:4] = steps
        outputs = {
            Path(alias) / "deploy/run.sh": shell.replace(
                "__RESOURCES__", " ".join(resources)
            ),
            Path(alias)
            / ".github/workflows/deploy.yaml": "# Generated by scripts/sync_deploy.py; do not edit.\n"
            + yaml.safe_dump(workflow, sort_keys=False, width=120),
        }
        for relative, expected in outputs.items():
            target = root / relative
            if not target.exists() or target.read_text() != expected:
                stale.append(relative)
                if not check:
                    target.write_text(expected)
    return stale


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = sync(check=args.check)
    if args.check and stale:
        parser.exit(
            1,
            "Stale deployments; run python3 scripts/sync_deploy.py:\n"
            + "\n".join(map(str, stale))
            + "\n",
        )
    print(
        f"Hosted deployment templates: {len(stale)} files {'stale' if args.check else 'updated'}"
    )


if __name__ == "__main__":
    main()
