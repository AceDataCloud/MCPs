"""Generate native Messages choices from a verified PlatformBackend contract bundle."""

import argparse
import hashlib
import json
from pathlib import Path


def render_models(bundle: Path) -> str:
    manifest = json.loads((bundle / "manifest.json").read_text())
    relative = "openapi/claude.json"
    raw = (bundle / relative).read_bytes()
    if manifest["files"][relative] != "sha256:" + hashlib.sha256(raw).hexdigest():
        raise ValueError("Messages contract does not match its bundle manifest")
    spec = json.loads(raw)

    def resolve(value):
        seen = set()
        while "$ref" in value:
            ref = value["$ref"]
            if not ref.startswith("#/") or ref in seen:
                raise ValueError("Expected a non-recursive local schema reference")
            seen.add(ref)
            value = spec
            for part in ref[2:].split("/"):
                value = value[part.replace("~1", "/").replace("~0", "~")]
        return value

    operation = spec["paths"]["/v1/messages"]["post"]
    body = resolve(operation["requestBody"])
    schema = resolve(body["content"]["application/json"]["schema"])
    models = resolve(schema["properties"]["model"])["enum"]
    if (
        not models
        or len(set(models)) != len(models)
        or not all(isinstance(item, str) for item in models)
    ):
        raise ValueError("Expected a nonempty unique model enum")
    if not {"model", "messages", "max_tokens"} <= set(schema["required"]):
        raise ValueError("Messages required fields changed; review the client before syncing")
    return (
        f'"""Generated by scripts/sync_messages_models.py from PlatformBackend {manifest["source_sha"]}."""\n\n'
        "from typing import Literal\n\n"
        "MessagesModel = Literal[\n"
        + "".join(f"    {json.dumps(model)},\n" for model in models)
        + "]\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bundle-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "core/messages_models.py"
    source = render_models(args.bundle_dir)
    if args.check:
        if not target.exists() or target.read_text() != source:
            raise SystemExit("Messages choices differ from the canonical contract bundle")
    else:
        target.write_text(source)


if __name__ == "__main__":
    main()
